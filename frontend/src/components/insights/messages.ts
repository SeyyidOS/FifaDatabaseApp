export type InsightT = Translate<typeof insightMessages.en>;

export const archetypeTitle = (t: InsightT, a: Archetype) => t(`${a.key}Title`);
export const archetypeBlurb = (t: InsightT, a: Archetype) => t(`${a.key}Blurb`, a.vars);

export const awardTitle = (t: InsightT, a: Award) => t(`${a.key}Title`);
export const awardCaption = (t: InsightT, a: Award) => t(`${a.key}Caption`);
export const awardDetail = (t: InsightT, a: Award) => t(`${a.key}Detail`, a.detail);

/** "+467 Elo", "+15.3", "+123" or "73%" depending on the award. */
export function awardValue(t: InsightT, a: Award, value = a.value): string {
  const sign = (v: number) => (v >= 0 ? "+" : "−");
  switch (a.format) {
    case "elo":
      return `${sign(value)}${Math.abs(Math.round(value))} Elo`;
    case "results":
      return `${sign(value)}${Math.abs(value).toFixed(1)}`;
    case "club":
      return `${sign(value)}${Math.abs(Math.round(value))}`;
    case "pct":
      return t("pct", { n: Math.round(value) });
  }
}
